int type_index(const char* key){
    if(key == nullptr){ return -1; }
    for(int i = 0; i < FOOD_TYPE_COUNT; i++){
        if(strcmp(key, FOOD_TYPES[i]) == 0){ return i; }
    }
    return -1;
}

bool type_valid(const char* key){
    return key != nullptr && (key[0] == '\0' || type_index(key) >= 0);
}

const uint8_t* icon_16(int index){
    return index >= 0 && index < FOOD_TYPE_COUNT ? ICONS_16[index] : nullptr;
}

const uint8_t* icon_10(int index){
    return index >= 0 && index < FOOD_TYPE_COUNT ? ICONS_10[index] : nullptr;
}

